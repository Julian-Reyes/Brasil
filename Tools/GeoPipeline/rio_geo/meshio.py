"""Minimal OBJ writer for Unreal import.

Coordinates are written as East/North/Up offsets in centimetres from a tile pivot. Verified with a
calibration import (Docs/Map/CoordinateSystem.md): Unreal's OBJ importer maps file (x, y, z) to
UE (x, -y, z) with no unit scaling, which is exactly our source frame (+X east, +Y south).
Faces are counter-clockwise when viewed from the side they face.
"""
from pathlib import Path

import numpy as np


class MeshBuilder:
    """Accumulates triangles per material slot. Vertices are (E, N, Z) metres relative to the pivot."""

    def __init__(self):
        self.parts = {}

    def add(self, material, verts, tris, normals=None):
        verts = np.asarray(verts, dtype=np.float64).reshape(-1, 3)
        tris = np.asarray(tris, dtype=np.int64).reshape(-1, 3)
        if not len(tris):
            return
        if normals is None:
            normals = face_normals_per_vertex(verts, tris)
        self.parts.setdefault(material, []).append((verts, tris, np.asarray(normals, dtype=np.float64)))

    @property
    def triangle_count(self):
        return sum(len(t) for chunks in self.parts.values() for _, t, _ in chunks)

    def write_obj(self, path, mtl_name, uv_scale_m=10.0):
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        lines = [f"# Generated by Tools/GeoPipeline - do not edit, regenerate instead", f"mtllib {mtl_name}"]
        offset = 1
        for material in sorted(self.parts):
            for verts, tris, normals in self.parts[material]:
                v = verts * 100.0
                lines.extend(f"v {x:.1f} {y:.1f} {z:.1f}" for x, y, z in v)
                lines.extend(f"vt {u:.4f} {w:.4f}" for u, w in verts[:, :2] / uv_scale_m)
                lines.extend(f"vn {x:.4f} {y:.4f} {z:.4f}" for x, y, z in normals)
            lines.append(f"usemtl {material}")
            for verts, tris, _ in self.parts[material]:
                t = tris + offset
                lines.extend(f"f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}" for a, b, c in t)
                offset += len(verts)
        path.write_text("\n".join(lines) + "\n")


def face_normals_per_vertex(verts, tris):
    n = np.zeros_like(verts)
    fn = np.cross(verts[tris[:, 1]] - verts[tris[:, 0]], verts[tris[:, 2]] - verts[tris[:, 0]])
    for k in range(3):
        np.add.at(n, tris[:, k], fn)
    length = np.linalg.norm(n, axis=1, keepdims=True)
    return n / np.where(length > 0, length, 1.0)


def write_mtl(path, palette):
    """palette: {material_name: (r, g, b)} linear 0..1."""
    lines = []
    for name, (r, g, b) in palette.items():
        lines += [f"newmtl {name}", f"Kd {r:.3f} {g:.3f} {b:.3f}", "Ks 0 0 0", ""]
    Path(path).write_text("\n".join(lines))
